// Scans public/projects/<slug>/ and writes data/projectImages.generated.ts.
// Drop images into a project's folder and they appear on the site automatically:
//   - cover image:   a file named  cover.(jpg|jpeg|png|webp|avif)
//   - gallery images: files named  gallery-1.jpg, gallery-2.jpg, ... (any order)
//   - if there is no "cover", the first image (alphabetically) becomes the cover
// This runs automatically before every build (see package.json "prebuild").

import { readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const projectsDir = join(root, "public", "projects");
const outFile = join(root, "data", "projectImages.generated.ts");

const IMG = /\.(jpe?g|png|webp|avif)$/i;
const isCover = (f) => /^cover\.(jpe?g|png|webp|avif)$/i.test(f);
const isGallery = (f) => /^gallery[-_]?\d+.*\.(jpe?g|png|webp|avif)$/i.test(f);

// natural sort so gallery-2 comes before gallery-10
const natural = (a, b) =>
  a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });

const urlFor = (slug, file) =>
  `/projects/${slug}/${encodeURIComponent(file)}`;

const manifest = {};

if (existsSync(projectsDir)) {
  for (const slug of readdirSync(projectsDir)) {
    const dir = join(projectsDir, slug);
    if (!statSync(dir).isDirectory()) continue;

    const files = readdirSync(dir).filter((f) => IMG.test(f));
    if (files.length === 0) continue;

    const coverFile = files.find(isCover);
    const galleryFiles = files.filter(isGallery).sort(natural);

    // leftovers = images that are neither the cover nor gallery-N
    const leftovers = files
      .filter((f) => !isCover(f) && !isGallery(f))
      .sort(natural);

    const cover = coverFile
      ? urlFor(slug, coverFile)
      : (galleryFiles[0] && urlFor(slug, galleryFiles[0])) ||
        (leftovers[0] && urlFor(slug, leftovers[0]));

    // gallery = explicit gallery-N files + any leftovers (keeps everything visible)
    const gallery = [...galleryFiles, ...leftovers].map((f) => urlFor(slug, f));

    manifest[slug] = { cover, gallery };
  }
}

const body = `// AUTO-GENERATED by scripts/generate-image-manifest.mjs — do not edit by hand.
// Run \`npm run build\` (or \`node scripts/generate-image-manifest.mjs\`) to refresh.

export interface ProjectImageSet {
  cover?: string;
  gallery: string[];
}

export const projectImages: Record<string, ProjectImageSet> = ${JSON.stringify(
  manifest,
  null,
  2,
)};
`;

writeFileSync(outFile, body, "utf8");

const count = Object.keys(manifest).length;
console.log(
  `[images] wrote ${outFile.replace(root + "\\", "").replace(root + "/", "")} — ${count} project(s) with images`,
);
